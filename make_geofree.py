# make_geofree.py - regenerate the AI-services hosts block (GeoFree method).
#
# Takeh1ko/GeoFree keeps AI services (ChatGPT, Claude, Gemini, Grok, ElevenLabs,
# Copilot) working without VPN by pinning their domains to a Comss Smart DNS
# proxy IP. That IP changes over time; the fresh one is obtained by resolving
# chatgpt.com through dns.comss.one. This script:
#   1. fetches the domain list from the GeoFree repo's GF_Windows.bat,
#   2. resolves the current Comss IP (falls back to the repo's default),
#   3. functional-tests it (real HTTPS probes for the main service families),
#   4. writes geofree_hosts.txt (priority: LAST in sources.txt - gap filler,
#      malw.link keeps OpenAI/Copilot, GeoFree adds Claude/Gemini/Grok/ElevenLabs).
import re
import socket
import ssl
import subprocess
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BAT_URL = "https://raw.githubusercontent.com/Takeh1ko/GeoFree/master/GF_Windows.bat"
COMSS_DNS = "dns.comss.one"
SEED_DOMAIN = "chatgpt.com"
OUT = ROOT / "geofree_hosts.txt"
PROBE_SET = ["chatgpt.com", "claude.ai", "gemini.google.com", "grok.com", "api.anthropic.com"]


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "hosts-merger/1.0"})
    return urllib.request.urlopen(req, timeout=60).read().decode("utf-8", errors="replace")


def probe(ip, sni, timeout=6):
    ctx = ssl.create_default_context()
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE
    try:
        with socket.create_connection((ip, 443), timeout=timeout) as sock:
            with ctx.wrap_socket(sock, server_hostname=sni) as tls:
                tls.sendall(f"GET / HTTP/1.1\r\nHost: {sni}\r\nUser-Agent: hosts-merger\r\nConnection: close\r\n\r\n".encode())
                data = tls.recv(128)
                if data.startswith(b"HTTP/"):
                    return data.split(b"\r\n", 1)[0].decode("utf-8", "replace")
    except OSError:
        pass
    return None


def resolve_comss(seed=SEED_DOMAIN):
    """nslookup <seed> dns.comss.one -> last A-record (their proxy IP)."""
    try:
        out = subprocess.run(["nslookup", seed, COMSS_DNS], capture_output=True, text=True, timeout=30)
        addrs = re.findall(r"Address:\s*(\d{1,3}(?:\.\d{1,3}){3})", out.stdout)
        # first address is the DNS server itself, take the last (the answer)
        if len(addrs) >= 2:
            return addrs[-1]
        if addrs:
            return addrs[0]
    except Exception as e:
        print(f"  ! comss resolve failed: {e}")
    return None


def main():
    bat = fetch(BAT_URL)
    m_dom = re.search(r'set "DOMAINS=([^"]+)"', bat)
    m_ip = re.search(r'set "DEFAULT_IP=([^"]+)"', bat)
    if not m_dom:
        print("could not parse DOMAINS from GF_Windows.bat - keeping existing file")
        return 1
    domains = sorted({d.lower().strip(".") for d in m_dom.group(1).split() if d.strip()})
    default_ip = m_ip.group(1) if m_ip else "91.207.75.110"

    ip = resolve_comss() or default_ip
    print(f"Comss proxy IP: {ip} (repo default: {default_ip})")

    print("Functional test (HTTPS through the IP):")
    results = {d: probe(ip, d) for d in PROBE_SET}
    for d, st in results.items():
        print(f"   {d}: {st or 'BROKEN'}")
    working = [d for d, st in results.items() if st]
    if not working:
        print("Comss IP does not answer for any AI service - keeping existing file")
        return 1

    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "# AUTO-GENERATED by make_geofree.py - DO NOT EDIT BY HAND",
        f"# Method: Takeh1ko/GeoFree (Comss Smart DNS {COMSS_DNS})",
        f"# Generated: {now}",
        f"# IP: {ip} ({len(working)}/{len(PROBE_SET)} service probes OK)",
        "",
    ]
    for d in domains:
        lines.append(f"{ip:<18} {d}")
    lines.append("")
    new_text = "\n".join(lines)
    strip = lambda s: [l for l in s.splitlines() if "Generated:" not in l]
    if OUT.exists() and strip(OUT.read_text(encoding="utf-8", errors="replace")) == strip(new_text):
        print(f"geofree_hosts.txt unchanged ({len(domains)} domains) - not rewritten")
        return 0
    OUT.write_text(new_text, encoding="utf-8", newline="\n")
    print(f"geofree_hosts.txt written: {len(domains)} domains on {ip}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
