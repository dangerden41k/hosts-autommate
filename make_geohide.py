# make_geohide.py - regenerate the whole GeoHide block with LIVE servers only.
#
# Problem this solves: the GeoHideDNS GitHub repo updates rarely (weeks apart),
# but their proxy servers rotate much faster - the repo keeps mapping domains to
# already-dead servers (2026-11-05: ALL 4 RU servers in the file were dead while
# EU servers were alive). This script:
#   1. downloads GeoHide RU + EU hosts files and the panel domain lists,
#   2. functionally tests every candidate server (HTTPS probe: panel test domain
#      first, then a real panel domain - "alive" means it actually proxies),
#   3. maps ALL GeoHide panel domains (incl. Supercell list + extras) onto the
#      alive servers round-robin,
#   4. writes geohide_ru_hosts.txt for merge_hosts.py (sources.txt).
import re
import socket
import ssl
import urllib.request
from collections import defaultdict
from datetime import datetime, timezone
from itertools import cycle
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BASE = "https://raw.githubusercontent.com/Internet-Helper/GeoHideDNS/main"
RU_URL = BASE + "/hosts/hosts"
EU_URL = BASE + "/hosts/eu/hosts"
LIST_URLS = [BASE + "/lists/supercell.txt", BASE + "/lists/domains.txt"]
OUT = ROOT / "geohide_ru_hosts.txt"
LOCAL_DOMAINS = {"localhost", "localhost.localdomain", "ip6-localhost"}
PROBE_SNI = "dnstest.geohide.ru"
IP_RE = re.compile(r"^\d{1,3}(\.\d{1,3}){3}$")


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "hosts-merger/1.0"})
    return urllib.request.urlopen(req, timeout=60).read().decode("utf-8", errors="replace")


def probe(ip, sni, timeout=6):
    """HTTP status line through this IP for SNI=sni, or None."""
    ctx = ssl.create_default_context()
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE
    try:
        with socket.create_connection((ip, 443), timeout=timeout) as sock:
            with ctx.wrap_socket(sock, server_hostname=sni) as tls:
                tls.sendall(f"GET / HTTP/1.1\r\nHost: {sni}\r\nUser-Agent: hosts-merger\r\nConnection: close\r\n\r\n".encode())
                data = tls.recv(128)
                if data.startswith(b"HTTP/"):
                    return data.split(b"\r\n", 1)[0].decode("utf-8", "replace")
    except OSError:
        pass
    return None


def main():
    ru_text = fetch(RU_URL)
    eu_text = fetch(EU_URL)

    per_domain = {}                  # domain -> original servers (RU file, first-seen order)
    candidates = set()               # every GeoHide server from both regions
    for text in (ru_text, eu_text):
        for raw in text.splitlines():
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) < 2:
                continue
            ip, dom = parts[0], parts[1].lower().strip(".")
            if not IP_RE.match(ip) or dom in LOCAL_DOMAINS:
                continue
            candidates.add(ip)
            if text is ru_text and dom not in per_domain:
                per_domain[dom] = ip   # keep first occurrence for reference only

    # extra panel-list domains (supercell games, cgtrader, chaos, ...)
    extra = set()
    for url in LIST_URLS:
        try:
            for l in fetch(url).splitlines():
                d = l.strip().lower().strip(".")
                if d and not d.startswith("#"):
                    extra.add(d)
        except Exception as e:
            print(f"  ! list fetch failed {url}: {e}")
    extra -= set(per_domain)

    if not per_domain:
        print("no domains parsed - keeping existing output")
        return 1

    print("GeoHide server functional test:")
    print("   (step 1: panel test domain, step 2: real panel domain)")
    sample = next((d for d in sorted(per_domain) if "geohide" not in d), None)
    alive = []
    for srv in sorted(candidates):
        st1 = probe(srv, PROBE_SNI)
        if not st1:
            print(f"   {srv}: dead")
            continue
        st2 = probe(srv, sample) if sample else None
        if st2:
            print(f"   {srv}: ALIVE + proxies panel domains ({st1} / {st2})")
            alive.append(srv)
        else:
            print(f"   {srv}: answers for geohide.ru only, does NOT proxy panel domains")

    if not alive:
        print("NO working GeoHide servers - keeping existing output unchanged")
        return 1
    print(f"Working servers: {alive}")

    domains = sorted(set(per_domain) | extra)
    rr = cycle(alive)
    chosen = {d: next(rr) for d in domains}

    used = defaultdict(int)
    for ip in chosen.values():
        used[ip] += 1
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "# AUTO-GENERATED by make_geohide.py - DO NOT EDIT BY HAND",
        f"# Sources: {RU_URL} (+ EU server list, + panel domain lists)",
        f"# Generated: {now}",
        f"# Working servers (functional-tested): {dict(used)}",
        "",
    ]
    for dom in sorted(chosen):
        lines.append(f"{chosen[dom]:<18} {dom}")
    lines.append("")
    new_text = "\n".join(lines)
    # skip write if only the timestamp changed (avoids commit spam on hourly runs)
    strip = lambda s: [l for l in s.splitlines() if "Generated:" not in l]
    if OUT.exists() and strip(OUT.read_text(encoding="utf-8", errors="replace")) == strip(new_text):
        print(f"geohide_ru_hosts.txt unchanged ({len(chosen)} domains) - not rewritten")
        return 0
    OUT.write_text(new_text, encoding="utf-8", newline="\n")
    print(f"geohide_ru_hosts.txt written: {len(chosen)} domains")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
