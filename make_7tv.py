# make_7tv.py - regenerate the 7TV hosts block via Comss Smart DNS.
# 7tv's own IPs are RKN-blocked (IP-level, no SNI dependence) so hosts can only
# work through a proxy IP. The Comss proxy (141.133.183.77 as of 2026-11-11)
# answers 200 for all 7tv domains. This script:
#   1. resolves each 7tv domain via dns.comss.one to get the CURRENT Comss IP,
#   2. functional-tests it (HTTPS probe per domain),
#   3. falls back to the last known-good IP from the existing file,
#   4. writes 7tv_hosts.txt (priority: ABOVE geohide in sources.txt).
import re
import socket
import ssl
import subprocess
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent
COMSS_DNS = "dns.comss.one"
DOMAINS = ["7tv.app", "7tv.io", "cdn.7tv.app", "api.7tv.app"]
OUT = ROOT / "7tv_hosts.txt"

ctx = ssl.create_default_context()
ctx.check_hostname = False
ctx.verify_mode = ssl.CERT_NONE


def probe(ip, sni, timeout=6):
    try:
        with socket.create_connection((ip, 443), timeout=timeout) as sock:
            with ctx.wrap_socket(sock, server_hostname=sni) as tls:
                tls.sendall(f"GET / HTTP/1.1\r\nHost: {sni}\r\nUser-Agent: hosts-merger\r\nConnection: close\r\n\r\n".encode())
                data = tls.recv(128)
                if data.startswith(b"HTTP/"):
                    return data.split(b"\r\n", 1)[0].decode("utf-8", "replace")
    except OSError:
        pass
    return None


def resolve_via_comss(dom):
    try:
        out = subprocess.run(["nslookup", dom, COMSS_DNS], capture_output=True, text=True, timeout=30)
        addrs = re.findall(r"Address:\s*(\d{1,3}(?:\.\d{1,3}){3})", out.stdout)
        return addrs[-1] if addrs else None
    except Exception:
        return None


def last_known_ip():
    if not OUT.exists():
        return None
    for l in OUT.read_text(encoding="utf-8", errors="replace").splitlines():
        s = l.strip()
        if s and not s.startswith("#"):
            return s.split()[0]
    return None


def main():
    ip = None
    for dom in DOMAINS:
        r = resolve_via_comss(dom)
        if r:
            ip = r
            break
    if not ip:
        ip = last_known_ip()
        print(f"Comss DNS gave nothing - falling back to last known IP: {ip}")
        if not ip:
            print("no IP available - keeping existing file")
            return 1

    print(f"Comss proxy IP: {ip}")
    results = {d: probe(ip, d) for d in DOMAINS}
    for d, st in results.items():
        print(f"   {d}: {st or 'BROKEN'}")
    working = [d for d, st in results.items() if st]
    if not working:
        print("IP dead for all 7tv domains - keeping existing file")
        return 1

    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "# AUTO-GENERATED by make_7tv.py - DO NOT EDIT BY HAND",
        f"# Method: Comss Smart DNS ({COMSS_DNS}) proxy IP for 7tv domains",
        f"# Generated: {now}",
        f"# IP: {ip} ({len(working)}/{len(DOMAINS)} probes OK)",
        "",
    ]
    for d in working:
        lines.append(f"{ip:<18} {d}")
    lines.append("")
    new_text = "\n".join(lines)
    strip = lambda s: [l for l in s.splitlines() if "Generated:" not in l]
    if OUT.exists() and strip(OUT.read_text(encoding="utf-8", errors="replace")) == strip(new_text):
        print(f"7tv_hosts.txt unchanged ({len(working)} domains) - not rewritten")
        return 0
    OUT.write_text(new_text, encoding="utf-8", newline="\n")
    print(f"7tv_hosts.txt written: {len(working)} domains on {ip}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
